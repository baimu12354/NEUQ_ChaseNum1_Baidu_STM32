#define func_abs(x) ((x) > 0 ? (x) : -(x))

void spi_write_8bit(uint8_t data)
{
    // 发送一个字节数据
    HAL_SPI_Transmit(&Hard_SPI_2_Handle, &data, 1, HAL_MAX_DELAY);
}

void spi_write_8bit_array(const uint8_t *data, uint16_t len)
{
    // 发送多个字节数据
    HAL_SPI_Transmit(&Hard_SPI_2_Handle, (uint8_t *)data, len, HAL_MAX_DELAY);
}

void spi_write_16bit(uint16_t data)
{
    // 发送一个字节数据
    uint8_t buffer[2];
    buffer[0] = (data >> 8) & 0xFF; // 高字节
    buffer[1] = data & 0xFF;        // 低字节
    HAL_SPI_Transmit(&Hard_SPI_2_Handle, buffer, 2, HAL_MAX_DELAY);
}

void spi_write_16bit_array(const uint16_t *data, uint16_t len)
{
    // 发送多个字节数据
    HAL_SPI_Transmit(&Hard_SPI_2_Handle, (uint8_t *)data, len * 2, HAL_MAX_DELAY);
}


