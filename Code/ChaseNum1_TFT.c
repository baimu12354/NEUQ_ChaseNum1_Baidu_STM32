uint16_t                   tft180_width_max    = 128;
uint16_t                   tft180_height_max   = 160;
static 	uint16_t                   tft180_pencolor     = TFT180_DEFAULT_PENCOLOR;          // 画笔颜色(字体色)
static 	uint16_t                   tft180_bgcolor      = TFT180_DEFAULT_BGCOLOR;           // 背景颜色

